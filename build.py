#!/usr/bin/env python3
"""Build the site's pages from template.html and the card folders.

Usage:
    python3 build.py           # write index.html and system-design.html
    python3 build.py --check   # exit 1 if either page is out of date (no write)

Pages (see PAGES below; each is a tab in the nav bar):
    index.html           Coding Solutions, one card per folder in problems/
    system-design.html   System Design, one card per folder in designs/

Layout:
    template.html                  shared page shell; build.py fills {{TITLE}}, {{SUBTITLE}}
                                   and the <!-- NAV -->, <!-- STYLES -->, <!-- PROBLEMS -->
                                   and <!-- VISUALS --> lines
    problems/NNNN-slug/  (and designs/NNNN-slug/, same rules)
        problem.html               the <details class="question"> card, where each
                                   code block is a placeholder:
                                   <div class="code-tabs" data-src="approach1"></div>
        approach1.py / .cpp / ...  the code for that placeholder, one file per language
        approach1.visual.js        optional step-by-step visualizer for that approach
        style.css                  optional styles for this card only (added to the page head)
        script.js                  optional script for this card only (runs before app.js)

Visualizer line markers:
    End a code line with a comment like `# @viz store` (or `// @viz store`) to name
    it. The marker is removed from the code shown on the page, and the visualizer
    highlights that line whenever a step says line: "store". Several names can share
    a line (`# @viz check, found`) and a name can be used on several lines.

Cards are ordered by folder name, so keep the 4-digit prefix (the LeetCode number
for problems/, a running number for designs/).
No third-party dependencies; needs Python 3.8+.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
TEMPLATE = ROOT / "template.html"

# One entry per page, in nav-bar order.
PAGES = [
    {
        "output": "index.html",
        "folder": "problems",
        "title": "Coding Solutions",
        "subtitle": "My notes and solutions. Click a question to expand it.",
    },
    {
        "output": "system-design.html",
        "folder": "designs",
        "title": "System Design",
        "subtitle": "How real systems work, with interactive walkthroughs. Click a question to expand it.",
    },
]

# Optional per-card files, added to the page once (not shown as code tabs).
CARD_STYLE = "style.css"
CARD_SCRIPT = "script.js"

# File extension -> tab label. Tabs appear in this order.
LANGUAGES = {
    ".py": "Python",
    ".cpp": "C++",
    ".java": "Java",
    ".js": "JavaScript",
    ".ts": "TypeScript",
    ".go": "Go",
    ".rs": "Rust",
    ".c": "C",
    ".cs": "C#",
    ".kt": "Kotlin",
    ".swift": "Swift",
}
VISUAL_SUFFIX = ".visual.js"

PLACEHOLDER = re.compile(r'^([ \t]*)<div class="code-tabs" data-src="([\w-]+)"></div>[ \t]*$', re.M)
FOLDER_NAME = re.compile(r"^\d{4}-[a-z0-9-]+$")
# Trailing "# @viz name" or "// @viz name, other" marker comment on a code line.
VIZ_MARKER = re.compile(r"[ \t]*(?:#|//)[ \t]*@viz[ \t]+([\w-]+(?:[ \t]*,[ \t]*[\w-]+)*)[ \t]*$")
GENERATED_NOTE = (
    "<!-- GENERATED by build.py. Don't edit this file directly:\n"
    "     edit template.html, problems/ or designs/, then run `python3 build.py`. -->\n"
)


class BuildError(Exception):
    pass


def indent(text, prefix):
    """Indent non-empty lines; keep blank lines empty."""
    return "\n".join(prefix + line if line.strip() else "" for line in text.split("\n"))


def is_code_file(path):
    return path.suffix in LANGUAGES and not path.name.endswith(VISUAL_SUFFIX) and path.name != CARD_SCRIPT


def check_script_safe(text, path, tag="script"):
    # Text is placed inside a <script> (or <style>) element; only its closing tag can end it early.
    if re.search(rf"</{tag}", text, re.I):
        raise BuildError(f"{path.relative_to(ROOT)}: contains '</{tag}', which would break the page")


def read_code(path):
    """Return (code shown on the page, {marker name: [1-based line numbers]})."""
    lines = path.read_text(encoding="utf-8").replace("\t", "    ").split("\n")
    # Trim blank lines at both ends, the same way the page does, so line numbers match.
    while lines and not lines[0].strip():
        lines.pop(0)
    while lines and not lines[-1].strip():
        lines.pop()

    markers = {}
    for number, line in enumerate(lines, start=1):
        match = VIZ_MARKER.search(line)
        if match:
            lines[number - 1] = line[: match.start()].rstrip()
            for name in re.split(r"[ \t]*,[ \t]*", match.group(1)):
                markers.setdefault(name, []).append(number)
        elif "@viz" in line:
            raise BuildError(
                f"{path.relative_to(ROOT)}:{number}: malformed @viz marker; "
                "use a trailing comment like `# @viz name` or `// @viz name`"
            )
    code = "\n".join(lines)
    check_script_safe(code, path)
    return code, markers


def render_code_tabs(folder, name, pad, visuals):
    files = sorted(
        (p for p in folder.glob(name + ".*") if is_code_file(p)),
        key=lambda p: list(LANGUAGES).index(p.suffix),
    )
    if not files:
        raise BuildError(f"{folder.name}: no code files found for data-src=\"{name}\"")

    attrs = ""
    visual = folder / (name + VISUAL_SUFFIX)
    if visual.exists():
        viz_id = f"{folder.name}/{name}"
        script = visual.read_text(encoding="utf-8").strip("\n")
        check_script_safe(script, visual)
        if f'DSAViz.register("{viz_id}"' not in script:
            raise BuildError(
                f"{visual.relative_to(ROOT)}: must call DSAViz.register(\"{viz_id}\", {{...}})"
            )
        visuals.append((viz_id, script))
        attrs = f' data-viz="{viz_id}"'

    parts = [f'{pad}<div class="code-tabs"{attrs}>']
    for path in files:
        code, markers = read_code(path)
        lines_attr = ""
        if markers:
            # Names are [\w-] and values are numbers, so the JSON needs no escaping
            # inside a single-quoted attribute.
            lines_attr = f" data-viz-lines='{json.dumps(markers, separators=(',', ':'))}'"
        parts.append(
            f'{pad}  <script type="text/plain" data-lang="{LANGUAGES[path.suffix]}"{lines_attr}>'
        )
        parts.append(indent(code, pad + "    "))
        parts.append(f"{pad}  </script>")
    parts.append(f"{pad}</div>")
    used = {p.name for p in files} | ({visual.name} if visual.exists() else set())
    return "\n".join(parts), used


def render_problem(folder, visuals):
    card_path = folder / "problem.html"
    if not card_path.exists():
        raise BuildError(f"{folder.name}: missing problem.html")
    card = card_path.read_text(encoding="utf-8").strip("\n")
    if not card.startswith('<details class="question"'):
        raise BuildError(f"{folder.name}/problem.html: must start with <details class=\"question\" ...>")

    used = set()

    def replace(match):
        html, files = render_code_tabs(folder, match.group(2), match.group(1), visuals)
        used.update(files)
        return html

    card = PLACEHOLDER.sub(replace, card)

    # Code or visual files that no placeholder points to are almost always a typo.
    unused = sorted(
        p.name
        for p in folder.iterdir()
        if (is_code_file(p) or p.name.endswith(VISUAL_SUFFIX)) and p.name not in used
    )
    if unused:
        raise BuildError(f"{folder.name}: files not referenced by any data-src: {', '.join(unused)}")
    return card


def find_marker(template, name):
    marker = re.search(rf"^([ \t]*)<!-- {name} -->[ \t]*$", template, re.M)
    if not marker:
        raise BuildError(f"template.html: missing the <!-- {name} --> line")
    return marker


def replace_marker(html, name, render):
    """Replace the <!-- name --> line with render(indent), keeping its indentation."""
    marker = find_marker(html, name)
    text = render(marker.group(1))
    end = marker.end()
    if not text and html[end : end + 1] == "\n":
        end += 1  # nothing to add: drop the marker's whole line
    return html[: marker.start()] + text + html[end:]


def script_block(pad, comment, script):
    return f"{pad}<!-- {comment} -->\n{pad}<script>\n{indent(script, pad + '  ')}\n{pad}</script>"


def build_page(template, page):
    base = ROOT / page["folder"]
    if not base.is_dir():
        raise BuildError(f"{page['folder']}/: folder not found")
    folders = sorted(p for p in base.iterdir() if p.is_dir())
    for f in folders:
        if not FOLDER_NAME.match(f.name):
            raise BuildError(f"{page['folder']}/{f.name}: folder names must look like 0001-two-sum")

    visuals, cards, styles, scripts = [], [], [], []
    for folder in folders:
        where = f"{page['folder']}/{folder.name}"
        cards.append((where, render_problem(folder, visuals)))
        style = folder / CARD_STYLE
        if style.exists():
            css = style.read_text(encoding="utf-8").strip("\n")
            check_script_safe(css, style, tag="style")
            styles.append((f"{where}/{CARD_STYLE}", css))
        script = folder / CARD_SCRIPT
        if script.exists():
            js = script.read_text(encoding="utf-8").strip("\n")
            check_script_safe(js, script)
            scripts.append((f"{where}/{CARD_SCRIPT}", js))

    html = template.replace("{{TITLE}}", page["title"]).replace("{{SUBTITLE}}", page["subtitle"])
    html = replace_marker(
        html,
        "NAV",
        lambda pad: "\n".join(
            f'{pad}<a href="./{p["output"]}"' + (' aria-current="page"' if p is page else "") + f'>{p["title"]}</a>'
            for p in PAGES
        ),
    )
    html = replace_marker(
        html,
        "STYLES",
        lambda pad: "\n".join(
            f"{pad}<!-- {name} -->\n{pad}<style>\n{indent(css, pad + '  ')}\n{pad}</style>" for name, css in styles
        ),
    )
    html = replace_marker(
        html,
        "PROBLEMS",
        lambda pad: "\n\n".join(f"{pad}<!-- ===== {where} ===== -->\n" + indent(card, pad) for where, card in cards),
    )
    html = replace_marker(
        html,
        "VISUALS",
        lambda pad: "\n".join(
            [script_block(pad, f"{page['folder']}/{viz_id}{VISUAL_SUFFIX}", s) for viz_id, s in visuals]
            + [script_block(pad, name, js) for name, js in scripts]
        ),
    )
    # Put the "generated" note right after <!DOCTYPE html>.
    doctype, sep, rest = html.partition("\n")
    return doctype + sep + GENERATED_NOTE + rest, len(folders), len(visuals)


def main():
    check = "--check" in sys.argv[1:]
    try:
        template = TEMPLATE.read_text(encoding="utf-8")
        built = [(page, *build_page(template, page)) for page in PAGES]
    except BuildError as e:
        print(f"build.py: error: {e}", file=sys.stderr)
        return 2

    stale = False
    for page, html, count, nviz in built:
        output = ROOT / page["output"]
        summary = f"{count} {'problems' if page['folder'] == 'problems' else 'cards'}, {nviz} visualizers"
        current = output.read_text(encoding="utf-8") if output.exists() else None
        if check:
            if current != html:
                print(f"{page['output']} is out of date. Run: python3 build.py", file=sys.stderr)
                stale = True
            else:
                print(f"{page['output']} is up to date ({summary}).")
        elif current == html:
            print(f"{page['output']} already up to date ({summary}).")
        else:
            output.write_text(html, encoding="utf-8")
            print(f"Wrote {page['output']} ({summary}).")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
