#!/usr/bin/env python3
"""Build index.html from template.html and the problems/ folder.

Usage:
    python3 build.py           # write index.html
    python3 build.py --check   # exit 1 if index.html is out of date (no write)

Layout:
    template.html                  page shell; contains a <!-- PROBLEMS --> line
    problems/NNNN-slug/
        problem.html               the <details class="question"> card, where each
                                   code block is a placeholder:
                                   <div class="code-tabs" data-src="approach1"></div>
        approach1.py / .cpp / ...  the code for that placeholder, one file per language

Problems are ordered by folder name, so keep the 4-digit LeetCode number prefix.
No third-party dependencies; needs Python 3.8+.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
TEMPLATE = ROOT / "template.html"
OUTPUT = ROOT / "index.html"
PROBLEMS = ROOT / "problems"

# File extension -> tab label. Tabs appear in this order.
LANGUAGES = {
    ".py": "Python",
    ".cpp": "C++",
    ".java": "Java",
    ".js": "JavaScript",
    ".ts": "TypeScript",
    ".go": "Go",
    ".rs": "Rust",
    ".c": "C",
    ".cs": "C#",
    ".kt": "Kotlin",
    ".swift": "Swift",
}

PLACEHOLDER = re.compile(r'^([ \t]*)<div class="code-tabs" data-src="([\w-]+)"></div>[ \t]*$', re.M)
FOLDER_NAME = re.compile(r"^\d{4}-[a-z0-9-]+$")
GENERATED_NOTE = (
    "<!-- GENERATED by build.py. Don't edit this file directly:\n"
    "     edit template.html or problems/, then run `python3 build.py`. -->\n"
)


class BuildError(Exception):
    pass


def indent(text, prefix):
    """Indent non-empty lines; keep blank lines empty."""
    return "\n".join(prefix + line if line.strip() else "" for line in text.split("\n"))


def render_code_tabs(folder, name, pad):
    files = sorted(
        (p for p in folder.glob(name + ".*") if p.suffix in LANGUAGES),
        key=lambda p: list(LANGUAGES).index(p.suffix),
    )
    if not files:
        raise BuildError(f"{folder.name}: no code files found for data-src=\"{name}\"")

    parts = [f'{pad}<div class="code-tabs">']
    for path in files:
        code = path.read_text(encoding="utf-8").replace("\t", "    ").strip("\n")
        # Code sits inside <script type="text/plain">; only "</script" can end it early.
        if re.search(r"</script", code, re.I):
            raise BuildError(f"{path.relative_to(ROOT)}: contains '</script', which would break the page")
        parts.append(f'{pad}  <script type="text/plain" data-lang="{LANGUAGES[path.suffix]}">')
        parts.append(indent(code, pad + "    "))
        parts.append(f"{pad}  </script>")
    parts.append(f"{pad}</div>")
    return "\n".join(parts), {p.name for p in files}


def render_problem(folder):
    card_path = folder / "problem.html"
    if not card_path.exists():
        raise BuildError(f"{folder.name}: missing problem.html")
    card = card_path.read_text(encoding="utf-8").strip("\n")
    if not card.startswith('<details class="question"'):
        raise BuildError(f"{folder.name}/problem.html: must start with <details class=\"question\" ...>")

    used = set()

    def replace(match):
        html, files = render_code_tabs(folder, match.group(2), match.group(1))
        used.update(files)
        return html

    card = PLACEHOLDER.sub(replace, card)

    # Code files that no placeholder points to are almost always a typo.
    unused = sorted(
        p.name for p in folder.iterdir() if p.suffix in LANGUAGES and p.name not in used
    )
    if unused:
        raise BuildError(f"{folder.name}: code files not referenced by any data-src: {', '.join(unused)}")
    return card


def build():
    template = TEMPLATE.read_text(encoding="utf-8")
    marker = re.search(r"^([ \t]*)<!-- PROBLEMS -->[ \t]*$", template, re.M)
    if not marker:
        raise BuildError("template.html: missing the <!-- PROBLEMS --> line")
    pad = marker.group(1)

    folders = sorted(p for p in PROBLEMS.iterdir() if p.is_dir())
    for f in folders:
        if not FOLDER_NAME.match(f.name):
            raise BuildError(f"problems/{f.name}: folder names must look like 0001-two-sum")

    cards = []
    for folder in folders:
        card = render_problem(folder)
        cards.append(
            f"{pad}<!-- ===== problems/{folder.name} ===== -->\n"
            + indent(card, pad)
        )

    html = template[: marker.start()] + "\n\n".join(cards) + template[marker.end():]
    # Put the "generated" note right after <!DOCTYPE html>.
    doctype, sep, rest = html.partition("\n")
    return doctype + sep + GENERATED_NOTE + rest, len(folders)


def main():
    check = "--check" in sys.argv[1:]
    try:
        html, count = build()
    except BuildError as e:
        print(f"build.py: error: {e}", file=sys.stderr)
        return 2

    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else None
    if check:
        if current != html:
            print("index.html is out of date. Run: python3 build.py", file=sys.stderr)
            return 1
        print(f"index.html is up to date ({count} problems).")
        return 0

    if current == html:
        print(f"index.html already up to date ({count} problems).")
    else:
        OUTPUT.write_text(html, encoding="utf-8")
        print(f"Wrote index.html ({count} problems).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
